def apply(data: list, syn: dict):
    """증상군 행마다 라벨이 표에 있으면 키워드를 보강한다. (바뀐 항목 수, 추가된 키워드 수, 못 쓴 라벨) 을 돌려준다."""
    changed = added = 0
    used = set()
    for group in data:
        if not isinstance(group, dict) or not group.get("symptom_key"):
            continue
        for sec in ("required_questions", "red_flags", "context_questions"):
            for item in group.get(sec) or []:
                extra = syn.get(item.get("label", ""))
                if not extra:
                    continue
                used.add(item["label"])
                kws = list(item.get("keywords") or [])
                before = len(kws)
                for k in extra:
                    if k not in kws:
                        kws.append(k)
                if len(kws) != before:
                    item["keywords"] = kws
                    changed += 1
                    added += len(kws) - before
    unused = sorted(set(syn) - used)
    return changed, added, unused


def ensure_version_row(data: list, version: str):
    """목록 맨 앞에 symptom_key 없는 판 표시 행 하나. 이미 있으면 값만 맞춘다."""
    rows = [r for r in data if isinstance(r, dict) and not r.get("symptom_key") and "version" in r]
    for r in rows:
        data.remove(r)
    data.insert(0, {
        "version": version,
        "note": "체크리스트 판 표시 행(증상군 아님). cl-v2: 라벨 기준 동의어 키워드 보강(REQ-TICC, 2026-10-19). "
                "판정기 sv-v3 는 라벨 또는 강한 키워드 1개로 '확인' 을 센다. "
                "증상군 행만 쓰려면 symptom_key 가 있는 행을 고른다(consultation_loader.load_checklists_raw).",
    })


