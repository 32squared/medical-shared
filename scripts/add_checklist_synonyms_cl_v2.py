    ap = argparse.ArgumentParser()
    ap.add_argument("--path", default=DEFAULT)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    with open(a.path, encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, list):
        print("list 꼴이 아닙니다:", type(data).__name__)
        return 2
    changed, added, unused = apply(data, SYN)
    ensure_version_row(data, VERSION)
    groups = [g for g in data if isinstance(g, dict) and g.get("symptom_key")]
    items = sum(len(g.get(s) or []) for g in groups for s in ("required_questions", "red_flags", "context_questions"))
    short = sorted({k for g in groups for s in ("required_questions", "red_flags", "context_questions")
                    for it in g.get(s) or [] for k in it.get("keywords") or [] if len(k) <= 2})
    print(f"[cl-v2] 증상군 {len(groups)} · 항목 {items} · 바뀐 항목 {changed} · 추가 키워드 {added} · 표에 있으나 안 쓰인 라벨 {len(unused)}")
